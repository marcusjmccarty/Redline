import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
import {dissolve} from './atlas-geometry.mjs';
const root=new URL('../',import.meta.url),context={window:{}};
vm.runInNewContext(await readFile(new URL('public/world.js',root),'utf8'),context);
const atlas=dissolve(context.window.WORLD_PATHS);
// Ship the lookup data alongside the dissolved coastlines. Loading world.js as
// well would download and parse every old country polygon a second time.
// Borders and regional lines ship in the atlas's own compact geography (public/atlas/), for the worker. Nothing at runtime reads the rest removed here.
const data={...context.window,ATLAS_LAND:atlas.land};delete data.WORLD_PATHS;delete data.REGION_PATHS;delete data.ANTARCTICA_POLYGONS;delete data.MAP_META;
await writeFile(new URL('public/atlas-geography.js',root),'/* Generated by scripts/build-atlas.mjs from the bundled world map. */\n'+Object.entries(data).map(([name,value])=>`window.${name}=${JSON.stringify(value)};`).join('\n')+'\n');
console.log(`Atlas: ${atlas.land.length} landmasses and ${atlas.borders.length} boundary groups.`);
